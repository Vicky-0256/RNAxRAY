func TestResearchPanelStatuses(t *testing.T) {
	a, f, tt, p := openResearch(t, true)
	r := p.research
	r.confirmed, r.taxon = true, ""
	look := func(id string) {
		t.Helper()
		r.identifier = id
		tt.Frame()
		mustClick(t, tt, "View existing summary")
		rsSettle(a, tt)
	}
	look("KX377335")
	mustHave(t, tt, "Not found or no summary", "found no entry, or no summary", "does not mean the RNA has not been studied", "KX377335 · no taxon")
	for _, text := range tt.Texts() {
		if strings.Contains(text, "No research") || strings.Contains(text, "not studied") {
			t.Fatalf("claims absence of research: %q", text)
		}
	}
	snapshot(t, tt, "research-not-found")
	look("timeout")
	mustHave(t, tt, "Timed out", "No answer within 45 s; the lookup was stopped. Nothing is concluded.", "no answer")
	if tt.HasText("Save to project") {
		t.Fatal("a timeout card can be saved")
	}
	look("other")
	mustHave(t, tt, "RNAcentral error", "could not be reached")

	// Cancel while running.
	r.identifier = "slow"
	tt.Frame()
	mustClick(t, tt, "View existing summary")
	tt.Frame()
	mustHave(t, tt, "Asking RNAcentral…", "Cancel")
	if r.running != "describe" {
		t.Fatalf("running %q", r.running)
	}
	mustClick(t, tt, "Cancel")
	for i := 0; i < 50 && r.running != ""; i++ {
		rsSettle(a, tt)
	}
	rsSettle(a, tt)
	mustHave(t, tt, "Cancelled", "The lookup was cancelled. Nothing is concluded.")
	_ = f

	// Check identifier needs the taxon and says the mapping is advisory.
	r.identifier, r.taxon = "hsa-mir-21", "9606"
	tt.Frame()
	mustClick(t, tt, "Check identifier")
	rsSettle(a, tt)
	mustHave(t, tt, "RNAcentral identifier check — advisory, not an identity decision", "No RNAcentral entry found for external ID: hsa-mir-21")
}

func TestResearchPanelOtherResultCards(t *testing.T) {
	a, f, tt, p := openResearch(t, true)
	digest := researchDigest(p.cache[structA].Records)
	elsewhere := rsCard("hsa-mir-21", "9606", model.EvidenceSuccess, rsSummary)
	elsewhere.EvidenceID = "ev-1111111111111111"
	elsewhere.Binding = &model.EvidenceBinding{StructureID: "structure-b", Record: "all", ResultDigest: digest}
	changed := rsCard("hsa-mir-155", "9606", model.EvidenceSuccess, "Another summary.")
	changed.EvidenceID = "ev-2222222222222222"
	changed.Binding = &model.EvidenceBinding{StructureID: structA, Record: "all", ResultDigest: model.EvidenceDigest("((..))")}
	f.saved = []model.EvidenceCard{elsewhere, changed}
	p.research.loadSaved()
	rsSettle(a, tt)
	mustHave(t, tt, "Saved for this result (0)", "Saved for other results (2) — not applied here",
		"hsa-mir-21 · Summary found · for another result (structure-b · all windows)",
		"hsa-mir-155 · Summary found · for another result ("+structA+" · all windows)")
	if tt.HasText("Another summary.") || tt.HasText("Include in report") {
		t.Fatal("a card of another result is reused here")
	}
}

