NOT_FOUND = "Error querying RNAcentral API: 404, message='Not Found', url='https://rnacentral.org/api/v1/litsumm/KX377335'"


def text_result(text, is_error=False):
    return SimpleNamespace(content=[SimpleNamespace(type="text", text=text)], isError=is_error)


class FakeClient:
    """Scripted stand-in for McpClient (no process)."""

    def __init__(self, outcomes):
        self.outcomes = list(outcomes)
        self.calls = []
        self.timeouts = []
        self.tools = ["get_rna_description", "map_rna_id"]
        self.connected = True

    def connect(self):
        return self.tools

    def call_tool(self, name, arguments, timeout=None):
        if name not in mcp_client.ALLOWED_TOOLS:
            raise mcp_client.ToolRefused(name)
        self.calls.append((name, dict(arguments)))
        self.timeouts.append(timeout)
        outcome = self.outcomes.pop(0)
        if callable(outcome):
            outcome = outcome()
        if isinstance(outcome, Exception):
            raise outcome
        return outcome

    def close(self):
        self.connected = False


class ClassificationTests(unittest.TestCase):
    def test_pinned_texts(self):
        self.assertEqual(classify_describe(NOT_FOUND), ("not_found_or_no_summary", "HTTP 404 Not Found"))
        self.assertEqual(classify_describe("Error querying RNAcentral API: 500, message='Internal Server Error', url='x'"),
                         ("upstream_error", "HTTP 500 Internal Server Error"))
        status, detail = classify_describe("Error querying RNAcentral API: Cannot connect to host rnacentral.org:443")
        self.assertEqual(status, "upstream_error")
        self.assertIn("Cannot connect", detail)
        self.assertEqual(classify_describe("Error querying RNAcentral API: "), ("upstream_error", "RNAcentral request failed"))
        self.assertEqual(classify_describe("No description available"), ("summary_unavailable", None))
        self.assertEqual(classify_describe(""), ("unexpected_response", "empty response"))
        self.assertEqual(classify_describe("  \n"), ("unexpected_response", "empty response"))
        self.assertEqual(classify_describe("WARNING: This summary was generated by AI. x"), ("success", None))

    def test_mapping_texts(self):
        self.assertEqual(classify_mapping("No RNAcentral entry found for external ID: hsa-mir-21", "9606")[0],
                         "not_found_or_no_summary")
        self.assertEqual(classify_mapping("Error looking up external ID X: HTTP 503", "9606")[0], "upstream_error")
        ok = "# ID Mapping for X\n\n**Primary ID**: `URS000075A546_9606`\n**NCBI Taxon ID**: `9606`"
        self.assertEqual(classify_mapping(ok, "9606"), ("success", None))
        self.assertIn("differs", classify_mapping(ok.replace("9606", "10090"), "9606")[1])
        self.assertEqual(classify_mapping("something else", "9606")[0], "unexpected_response")

    def test_source_identifiers_only_present_tokens(self):
        text = "a [PMC5549916, PMC123] b PMID: 99887766 c doi:10.1093/nar/gkab123. PMC5549916 again"
        self.assertEqual(source_identifiers(text), ["PMC5549916", "PMC123", "PMID:99887766", "10.1093/nar/gkab123"])
        self.assertEqual(source_identifiers("no citations here"), [])
        self.assertEqual(source_identifiers(None), [])

    def test_source_url(self):
        self.assertEqual(source_url("URS000075A546_9606"), "https://rnacentral.org/rna/URS000075A546/9606")
        self.assertEqual(source_url("URS000075A546"), "https://rnacentral.org/rna/URS000075A546")
        self.assertIsNone(source_url("hsa-mir-21"))
        self.assertEqual(source_url("x", "**Primary ID**: `URS000075A546_10090`"),
                         "https://rnacentral.org/rna/URS000075A546/10090")


class ServiceTests(unittest.TestCase):
    def service(self, outcomes, cache=None):
        client = FakeClient(outcomes)
        return EvidenceService(client=client, cache=cache or EvidenceCache(None)), client

    def test_card_shape_and_digest(self):
        raw = "WARNING: This summary was generated by AI. See [PMC5549916]."
        service, client = self.service([text_result(raw)])
        response = service.describe({"operation": "describe", "rna_id": "hsa-mir-21", "taxon": "9606",
                                     "identity_confirmation": "user_confirmed"})
        card = response["card"]
        self.assertEqual(client.calls, [("get_rna_description", {"rna_id": "hsa-mir-21"})])
        self.assertEqual(card["status"], "success")
        self.assertEqual(card["content_kind"], "external_ai_summary")
        self.assertEqual(card["display_text"], raw)
        self.assertEqual(response["raw_text"], raw)
        self.assertEqual(card["raw_response_digest"], "sha256:" + hashlib.sha256(raw.encode()).hexdigest())
        self.assertEqual(card["source_identifiers"], ["PMC5549916"])
        self.assertEqual(card["identity_confirmation"], "user_confirmed")
        self.assertEqual(card["adapter_version"], ADAPTER_VERSION)
        self.assertRegex(card["evidence_id"], r"^ev-[0-9a-f]{32}$")
        self.assertEqual(card["review"], {"state": "unreviewed", "reviewer": None, "at": None})
        for field, value in (("citation_verification", "not_checked"), ("relation_to_current_structure", "background_only"),
                             ("raw_response_local_ref", None), ("binding", None), ("schema_version", "1.0"),
                             ("source_provider", "RNAcentral")):
            self.assertEqual(card[field], value)
        self.assertRegex(card["requested_at"], r"^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$")

    def test_404_has_no_display_text_and_is_not_retried(self):
        service, client = self.service([text_result(NOT_FOUND)])
        card = service.describe({"operation": "describe", "rna_id": "KX377335"})["card"]
        self.assertEqual((card["status"], card["status_detail"], card["display_text"]),
                         ("not_found_or_no_summary", "HTTP 404 Not Found", None))
        self.assertEqual(card["identity_confirmation"], "unconfirmed")
        self.assertEqual(len(client.calls), 1)

    def test_a_failing_local_helper_is_a_local_error(self):
        # The MCP server is a process on this computer: its loss is not an
        # RNAcentral (network) error. One restart is tried.
        service, client = self.service([mcp_client.ConnectionLost("MCP server unavailable: boom"),
                                        mcp_client.ConnectionLost("MCP server unavailable: boom")])
        card = service.describe({"operation": "describe", "rna_id": "hsa-mir-21"})["card"]
        self.assertEqual(card["status"], "local_error")
        self.assertIn("boom", card["status_detail"])
        self.assertEqual(len(client.calls), 2)

    def test_the_request_budget_bounds_calls_and_the_retry(self):
        import time as _time
        def slow_loss():
            _time.sleep(0.2)
            return mcp_client.ConnectionLost("lost")
        service, client = self.service([slow_loss, text_result("x")])
        service.budget, service.retry_min = 0.3, 0.2
        card = service.describe({"operation": "describe", "rna_id": "hsa-mir-21"})["card"]
        self.assertEqual(card["status"], "local_error")
        self.assertEqual(len(client.calls), 1, "retried without the time for it")
        self.assertLessEqual(client.timeouts[0], 0.3)

    def test_the_default_budget_fits_go_s_deadline(self):
        from desktop.runtime.evidence import rnacentral
        self.assertLessEqual(rnacentral.REQUEST_BUDGET + 5, 45)

    def test_text_with_other_content_is_unexpected(self):
        # Text plus an image or resource is not the plain summary this
        # version understands: nothing of it is shown as a summary.
        mixed = SimpleNamespace(content=[SimpleNamespace(type="text", text="Summary text."),
                                         SimpleNamespace(type="image", data="AAAA")], isError=False)
        service, _ = self.service([mixed])
        card = service.describe({"operation": "describe", "rna_id": "hsa-mir-21"})["card"]
        self.assertEqual(card["status"], "unexpected_response")
        self.assertIn("image", card["status_detail"])
        self.assertIsNone(card["display_text"])

    def test_is_error_precedes_known_texts(self):
        service, _ = self.service([text_result("No description available", is_error=True)])
        self.assertEqual(service.describe({"operation": "describe", "rna_id": "x1"})["card"]["status"], "upstream_error")

    def test_connection_errors_retry_once(self):
        lost = mcp_client.ConnectionLost("gone")
        service, client = self.service([lost, lost, lost])
        card = service.describe({"operation": "describe", "rna_id": "x1"})["card"]
        self.assertEqual(card["status"], "local_error")
        self.assertIsNone(card["raw_response_digest"])
        self.assertEqual(len(client.calls), 2)
        service, client = self.service([mcp_client.CallTimeout("slow"), text_result("ok")])
        self.assertEqual(service.describe({"operation": "describe", "rna_id": "x1"})["card"]["status"], "timeout")
        self.assertEqual(len(client.calls), 1)

    def test_validation_rejects_private_looking_input(self):
        service, client = self.service([])
        for request in ({"operation": "describe", "rna_id": "/Users/me/project/x.fa"},
                        {"operation": "describe", "rna_id": "a" * 101},
                        {"operation": "describe", "rna_id": ""},
                        {"operation": "describe", "rna_id": 5},
                        {"operation": "describe", "rna_id": "x1", "path": "/tmp/p"},
                        {"operation": "describe", "rna_id": "x1", "project_id": "p"},
                        {"operation": "describe", "rna_id": "x1", "force": "yes"},
                        {"operation": "map_id", "identifier": "x1"},
                        {"operation": "map_id", "identifier": "x1", "taxon": "../../etc"},
                        {"operation": "map_id", "identifier": "x1", "taxon": "12345678901"},
                        {"operation": "map_id", "identifier": "x1", "taxon": "Homo_sapiens"},
                        {"operation": "map_id", "identifier": "x1", "taxon": "H" * 65},
                        {"operation": "map_id", "identifier": "x 1", "taxon": "9606"}):
            with self.assertRaises(ValueError, msg=request):
                getattr(service, request["operation"])(request)
        self.assertEqual(client.calls, [])

    def test_identifier_and_taxon_rules_match_go(self):
        outcomes = [text_result("# ID Mapping for x")] * 4 + [text_result("ok")] * 2
        service, client = self.service(outcomes)
        for identifier, taxon in (("ENA|KX377335", "9606"), ("a" * 100, "1234567890"),
                                  ("URS000075A546_9606", "Homo sapiens"), ("x:1-2.3", "S. cerevisiae-x")):
            card = service.map_id({"operation": "map_id", "identifier": identifier, "taxon": taxon})["card"]
            self.assertEqual((card["query_identifier"], card["taxon"]), (identifier, taxon))
        service.describe({"operation": "describe", "rna_id": "_lead|underscore"})
        service.describe({"operation": "describe", "rna_id": "x1", "taxon": "H" * 64})
        self.assertEqual(len(client.calls), 6)

    def test_allowlist_refusal_in_client(self):
        client = mcp_client.McpClient(server_args=["-c", "raise SystemExit(1)"])
        with self.assertRaises(mcp_client.ToolRefused):
            client.call_tool("query_rnacentral", {"query": "x"})
        self.assertEqual(client.started_sessions, 0)
        client.close()


class CacheTests(unittest.TestCase):
    def test_hit_force_expiry_clear(self):
        with tempfile.TemporaryDirectory() as tmp:
            now = [1_000_000.0]
            cache = EvidenceCache(Path(tmp) / "cache", clock=lambda: now[0])
            raw = "WARNING: This summary was generated by AI. [PMC1]"
            client = FakeClient([text_result(raw), text_result(raw), text_result(raw), text_result(raw)])
            service = EvidenceService(client=client, cache=cache, clock=lambda: now[0])
            request = {"operation": "describe", "rna_id": "hsa-mir-21", "taxon": "9606"}
            first = service.describe(request)
            second = service.describe(request)
            self.assertFalse(first["cached"])
            self.assertTrue(second["cached"])
            self.assertEqual(len(client.calls), 1)
            self.assertNotEqual(first["card"]["evidence_id"], second["card"]["evidence_id"])
            self.assertEqual(second["card"]["retrieved_at"], first["card"]["retrieved_at"])
            self.assertEqual(second["card"]["raw_response_digest"], first["card"]["raw_response_digest"])
            service.describe(dict(request, force=True))
            self.assertEqual(len(client.calls), 2)
            service.describe(dict(request, taxon="10090"))  # different key
            self.assertEqual(len(client.calls), 3)
            now[0] += 7 * 24 * 3600  # expired
            self.assertFalse(service.describe(request)["cached"])
            self.assertEqual(len(client.calls), 4)
            files = list((Path(tmp) / "cache").iterdir())
            self.assertTrue(files)
            entry = json.loads(files[0].read_text())
            self.assertEqual(set(entry), {"key", "raw_text", "retrieved_at", "stored_at"})
            (Path(tmp) / "cache" / "unrelated.txt").write_text("keep")
            self.assertEqual(cache.clear(), 2)
            self.assertEqual([p.name for p in (Path(tmp) / "cache").iterdir()], ["unrelated.txt"])

    def test_errors_and_timeouts_are_not_cached(self):
        with tempfile.TemporaryDirectory() as tmp:
            cache = EvidenceCache(tmp)
            client = FakeClient([text_result("Error querying RNAcentral API: 500, message='x', url='y'"),
                                 mcp_client.CallTimeout("slow"), text_result("ok text")])
            service = EvidenceService(client=client, cache=cache)
            for _ in range(3):
                service.describe({"operation": "describe", "rna_id": "x1"})
            self.assertEqual(len(client.calls), 3)

    def test_key_mismatch_and_future_entries_are_ignored(self):
        with tempfile.TemporaryDirectory() as tmp:
            cache = EvidenceCache(tmp, clock=lambda: 1000.0)
            key = cache_key("RNAcentral", "get_rna_description", "x1", None, "0.1.1", ADAPTER_VERSION)
            cache.put(key, "text", None)
            self.assertEqual(cache.get(key)["raw_text"], "text")
            self.assertIsNone(cache.get(cache_key("RNAcentral", "get_rna_description", "x1", None, "0.1.2", ADAPTER_VERSION)))
            future = EvidenceCache(tmp, clock=lambda: 0.0)
            self.assertIsNone(future.get(key))


class ServerLogTests(unittest.TestCase):
    def test_server_log_is_off_unless_asked_and_never_appends(self):
        import os
        from unittest import mock
        with tempfile.TemporaryDirectory() as tmp:
            old = Path(tmp) / "rnacentral-server.log"
            old.write_text("litsumm/hsa-mir-21\n", encoding="utf-8")
            with mock.patch.dict(os.environ, {}, clear=False):
                os.environ.pop("RNAXRAY_EVIDENCE_SERVER_LOG", None)
                client = mcp_client.McpClient(log_dir=tmp)
                handle_ = client._errlog_file()
                self.assertEqual(handle_.name, os.devnull)
                client.close()
            self.assertFalse(old.exists(), "the old server log (queried ids) is kept")
            old.write_text("old session\n", encoding="utf-8")
            with mock.patch.dict(os.environ, {"RNAXRAY_EVIDENCE_SERVER_LOG": "1"}):
                client = mcp_client.McpClient(log_dir=tmp)
                client._errlog_file().write("new session\n")
                client.close()
            self.assertEqual(old.read_text(encoding="utf-8"), "new session\n")


