"""Fake RNAcentral MCP server for the evidence tests (FastMCP over stdio).

Behaviour is chosen by the identifier; ``--state DIR`` receives the pid, the
environment names and every tools/call (name, arguments, time).
"""
import argparse
import asyncio
import json
import os
from pathlib import Path
import time

from mcp.server.fastmcp import FastMCP, Image

parser = argparse.ArgumentParser()
parser.add_argument("--state", required=True)
STATE = Path(parser.parse_args().state)
STATE.mkdir(parents=True, exist_ok=True)
(STATE / ("pid-%d" % os.getpid())).write_text(str(os.getpid()))
(STATE / "env.json").write_text(json.dumps(sorted(os.environ)))

SUMMARY = ("WARNING: This summary was generated by AI.\n\n"
           "hsa-mir-21 is an oncomiR [PMC5549916, PMC3456789]. See also PMID: 12345678 and "
           "doi:10.1093/nar/gkab123. PMC5549916 is cited twice.")
NOT_FOUND = ("Error querying RNAcentral API: 404, message='Not Found', "
             "url='https://rnacentral.org/api/v1/litsumm/%s'")


class RecordingFastMCP(FastMCP):
    async def call_tool(self, name, arguments):
        with open(STATE / "calls.jsonl", "a") as handle:
            handle.write(json.dumps({"name": name, "arguments": arguments, "t": time.time()}) + "\n")
        return await super().call_tool(name, arguments)


mcp = RecordingFastMCP("Fake RNAcentral MCP Server")


@mcp.tool()
async def get_rna_description(rna_id: str):
    if rna_id == "fake-404":
        return NOT_FOUND % rna_id
    if rna_id == "fake-500":
        return ("Error querying RNAcentral API: 500, message='Internal Server Error', "
                "url='https://rnacentral.org/api/v1/litsumm/fake-500'")
    if rna_id == "fake-connerr":
        return ("Error querying RNAcentral API: Cannot connect to host rnacentral.org:443 "
                "ssl:default [nodename nor servname provided, or not known]")
    if rna_id == "fake-nodesc":
        return "No description available"
    if rna_id == "fake-empty":
        return ""
    if rna_id == "fake-image":
        return Image(data=b"\x89PNG\r\n\x1a\n", format="png")
    if rna_id == "fake-iserror":
        raise ValueError("boom")
    if rna_id == "fake-sleep":
        await asyncio.sleep(60)
        return SUMMARY
    if rna_id == "fake-crash":
        os._exit(3)
    if rna_id == "fake-crash-once":
        marker = STATE / "crashed-once"
        if not marker.exists():
            marker.write_text("1")
            os._exit(3)
        return SUMMARY
    if rna_id == "fake-big":
        return "x" * (300 * 1024)
    return SUMMARY


@mcp.tool()
async def map_rna_id(identifier: str, taxon: str | None = None) -> str:
    if identifier == "fake-map-none":
        return "No RNAcentral entry found for external ID: %s" % identifier
    if identifier == "fake-map-error":
        return "Error looking up external ID %s: HTTP 503" % identifier
    returned = "10090" if identifier == "fake-map-mouse" else (taxon or "9606")
    return ("# ID Mapping for %s\n\n**Primary ID**: `URS000075A546_%s`\n**NCBI Taxon ID**: `%s`\n"
            "**Canonical ID**: `miRBase: MI0000077`" % (identifier, returned, returned))


@mcp.tool()
async def query_rnacentral(query: str) -> str:
    return "extra tool must never be called"


if __name__ == "__main__":
    mcp.run()
