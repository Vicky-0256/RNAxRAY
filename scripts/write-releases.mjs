#!/usr/bin/env node
// Writes web/releases.js: the published RNAxRay Desktop releases (newest
// first) and their files, for the Desktop drawer's version list. The site
// makes no requests of its own, so the list is fetched here, when the site is
// deployed (.github/workflows/deploy-pages.yml), and the release workflow
// redeploys the site after each release.
//
//   GITHUB_TOKEN=... node scripts/write-releases.mjs [owner/repo]
//
// Without a token the GitHub API allows 60 requests an hour. If the API
// cannot be read, web/releases.js is left as it is and the script warns.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const repo = process.argv[2] || process.env.GITHUB_REPOSITORY || "Vicky-0256/RNAxRAY";
const out = fileURLToPath(new URL("../web/releases.js", import.meta.url));
const MAX_RELEASES = 12;

const headers = { Accept: "application/vnd.github+json", "User-Agent": "rnaxray-write-releases" };
if (process.env.GITHUB_TOKEN) {
  headers.Authorization = "Bearer " + process.env.GITHUB_TOKEN;
}

let list;
try {
  const response = await fetch("https://api.github.com/repos/" + repo + "/releases?per_page=50", { headers });
  if (!response.ok) {
    throw new Error("HTTP " + response.status);
  }
  list = await response.json();
} catch (error) {
  console.warn("write-releases: could not read the releases of " + repo + " (" + error.message + "); web/releases.js unchanged");
  process.exit(0);
}

const releases = list
  .filter(function (release) { return !release.draft && !release.prerelease && /^v\d/.test(release.tag_name); })
  .sort(function (a, b) { return String(b.published_at).localeCompare(String(a.published_at)); })
  .slice(0, MAX_RELEASES)
  .map(function (release) {
    return {
      tag: release.tag_name,
      published: String(release.published_at || "").slice(0, 10),
      files: release.assets.map(function (asset) { return asset.name; }).sort()
    };
  });

writeFileSync(out, "// Generated by scripts/write-releases.mjs from the GitHub releases of " + repo + ".\n" +
  "window.RNAXRAY_RELEASES = " + JSON.stringify(releases, null, 2) + ";\n");
console.log("write-releases: " + releases.length + " releases → web/releases.js (" +
  releases.map(function (release) { return release.tag; }).join(", ") + ")");
